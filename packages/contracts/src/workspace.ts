// ---------------------------------------------------------------------------
// @ide/contracts – Workspace Metadata Types
// ---------------------------------------------------------------------------
// Source-only contracts for identifying and listing user workspaces.

/** Folder used as the workspace metadata marker at a workspace root. */
export const WORKSPACE_MARKER_FOLDER = '.ide' as const;

/** Alias for consumers that prefer an explicit name suffix. */
export const WORKSPACE_MARKER_FOLDER_NAME = WORKSPACE_MARKER_FOLDER;

/** User-profile registry key/name for persisted workspace metadata. */
export const USER_WORKSPACE_REGISTRY_KEY = 'ide.workspaces' as const;

/** Shape/version identifier for the user workspace registry contract. */
export const WORKSPACE_REGISTRY_VERSION = 1 as const;

/** Metadata describing one known IDE workspace. */
export interface WorkspaceInfo {
  /** Stable workspace identifier generated by the concrete adapter. */
  id: string;
  /** Human-readable workspace name. */
  name: string;
  /** Absolute or adapter-specific workspace root path/URI. */
  rootPath: string;
  /** Workspace marker folder name. Defaults to `.ide` for this contract version. */
  markerFolder?: typeof WORKSPACE_MARKER_FOLDER;
  /** ISO-8601 timestamp for when the workspace was first registered. */
  createdAt?: string;
  /** ISO-8601 timestamp for the last successful workspace open/ensure. */
  lastOpenedAt?: string;
}

/** User-level registry of workspaces known to the IDE. */
export interface WorkspaceRegistry {
  /** Registry schema version. */
  version?: typeof WORKSPACE_REGISTRY_VERSION;
  /** Known workspaces for the current user/profile. */
  workspaces: WorkspaceInfo[];
  /** Workspace selected or opened most recently, when known. */
  currentWorkspaceId?: string | null;
}
